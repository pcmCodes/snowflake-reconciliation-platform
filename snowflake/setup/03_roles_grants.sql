-- =============================================================================
-- 03_roles_grants.sql
-- RBAC: least-privilege functional roles, separation of duties (SOX/ITGC aligned).
-- In production, grant these functional roles to NAMED USERS, not to ACCOUNTADMIN.
-- =============================================================================

-- Functional roles -----------------------------------------------------------
CREATE OR REPLACE ROLE RECON_ADMIN;     -- platform owner: provisioning + grants oversight
CREATE OR REPLACE ROLE RECON_ENGINEER;  -- builds & runs pipelines (Bronze->Gold)
CREATE OR REPLACE ROLE RECON_ANALYST;    -- reads Gold + semantic for QA/dashboards
CREATE OR REPLACE ROLE RECON_READER;     -- dashboard consumers (semantic only)

-- Role hierarchy -------------------------------------------------------------
GRANT ROLE RECON_ENGINEER TO ROLE RECON_ADMIN;
GRANT ROLE RECON_ANALYST  TO ROLE RECON_ADMIN;
GRANT ROLE RECON_READER   TO ROLE RECON_ANALYST;   -- analysts inherit reader access

-- Database usage -------------------------------------------------------------
GRANT USAGE ON DATABASE RECON_PLATFORM TO ROLE RECON_ENGINEER;
GRANT USAGE ON DATABASE RECON_PLATFORM TO ROLE RECON_ANALYST;
GRANT USAGE ON DATABASE RECON_PLATFORM TO ROLE RECON_READER;

-- Schema usage + build privileges (engineers can create objects) -------------
GRANT ALL PRIVILEGES ON SCHEMA RECON_PLATFORM.BRONZE   TO ROLE RECON_ENGINEER;
GRANT ALL PRIVILEGES ON SCHEMA RECON_PLATFORM.SILVER   TO ROLE RECON_ENGINEER;
GRANT ALL PRIVILEGES ON SCHEMA RECON_PLATFORM.GOLD     TO ROLE RECON_ENGINEER;
GRANT ALL PRIVILEGES ON SCHEMA RECON_PLATFORM.SEMANTIC TO ROLE RECON_ENGINEER;

GRANT USAGE ON SCHEMA RECON_PLATFORM.GOLD     TO ROLE RECON_ANALYST;
GRANT USAGE ON SCHEMA RECON_PLATFORM.SEMANTIC TO ROLE RECON_ANALYST;
GRANT USAGE ON SCHEMA RECON_PLATFORM.SEMANTIC TO ROLE RECON_READER;

-- Future grants: tables/views created LATER inherit these automatically ------
-- (so RBAC need not be re-applied after every new object)
GRANT ALL PRIVILEGES ON FUTURE TABLES IN SCHEMA RECON_PLATFORM.BRONZE  TO ROLE RECON_ENGINEER;
GRANT ALL PRIVILEGES ON FUTURE TABLES IN SCHEMA RECON_PLATFORM.SILVER TO ROLE RECON_ENGINEER;
GRANT ALL PRIVILEGES ON FUTURE TABLES IN SCHEMA RECON_PLATFORM.GOLD    TO ROLE RECON_ENGINEER;
GRANT SELECT          ON FUTURE TABLES IN SCHEMA RECON_PLATFORM.GOLD    TO ROLE RECON_ANALYST;
GRANT SELECT          ON FUTURE TABLES IN SCHEMA RECON_PLATFORM.GOLD    TO ROLE RECON_READER;
GRANT SELECT          ON FUTURE VIEWS  IN SCHEMA RECON_PLATFORM.SEMANTIC TO ROLE RECON_ANALYST;
GRANT SELECT          ON FUTURE VIEWS  IN SCHEMA RECON_PLATFORM.SEMANTIC TO ROLE RECON_READER;

-- Warehouse usage ------------------------------------------------------------
GRANT USAGE ON WAREHOUSE RECON_LOAD_WH     TO ROLE RECON_ENGINEER;
GRANT USAGE ON WAREHOUSE RECON_TRANSFORM_WH TO ROLE RECON_ENGINEER;
GRANT USAGE ON WAREHOUSE RECON_REPORTING_WH TO ROLE RECON_ANALYST;
GRANT USAGE ON WAREHOUSE RECON_REPORTING_WH TO ROLE RECON_READER;
